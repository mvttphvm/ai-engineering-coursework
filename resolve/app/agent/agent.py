"""The support-ops agent loop.

    classify -> retrieve -> draft -> [HUMAN APPROVAL GATE] -> act

The gate is the design's center: without explicit approval the agent is
read-only — it can think and draft, but it cannot touch the ticket system.
Every step is recorded in `steps` (the run trace) so a human can audit
exactly what the agent did and why.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from app.agent.classify import classify_ticket
from app.agent.github_client import GitHubIssuesClient
from app.config import Settings
from app.logging_config import get_logger
from app.providers.base import ProviderError
from app.providers.factory import generate_with_fallback
from app.retrieval.search import HybridSearcher

log = get_logger(__name__)

MAX_DRAFT_SOURCES = 3


@dataclass
class AgentResult:
    category: str
    priority: str
    draft: str
    sources: list[str] = field(default_factory=list)
    status: str = "awaiting_approval"   # awaiting_approval | acted | no_evidence
    action: dict | None = None
    steps: list[str] = field(default_factory=list)


class SupportAgent:
    def __init__(self, searcher: HybridSearcher, settings: Settings,
                 github: GitHubIssuesClient | None = None) -> None:
        self.searcher = searcher
        self.settings = settings
        self.github = github or GitHubIssuesClient(
            token=settings.github_token,
            repo=settings.github_repo,
            dry_run=settings.agent_dry_run,
        )

    # -- steps ------------------------------------------------------------
    def _classify(self, title: str, body: str, steps: list[str]) -> tuple[str, str]:
        category, priority = classify_ticket(title, body)
        steps.append(f"classify: category={category} priority={priority}")
        return category, priority

    def _retrieve(self, title: str, body: str, steps: list[str]):
        query = f"{title} {body}".strip()
        results = self.searcher.search(query, top_k=MAX_DRAFT_SOURCES)
        kept = [r for r in results if r.cosine >= self.settings.ask_min_cosine]
        steps.append(f"retrieve: {len(results)} candidates, "
                     f"{len(kept)} above evidence threshold")
        return kept

    def _draft(self, title: str, body: str, results, steps: list[str]) -> str:
        if not results:
            steps.append("draft: skipped (no evidence)")
            return (
                "Thanks for reaching out. I don't have a knowledge-base "
                "article that covers this yet, so I've flagged your ticket "
                "for a human agent who can help directly."
            )
        # Same source-block shape as the RAG prompt (app/rag.build_prompt),
        # so every provider — real or fake — sees one consistent format.
        context = "\n\n".join(
            f"[{i}] Source: {r.chunk.source} — {r.chunk.title}\n{r.chunk.text}"
            for i, r in enumerate(results, start=1)
        )
        prompt = (
            "Draft a helpful, concise support reply to this ticket using "
            "ONLY the knowledge-base excerpts. Cite excerpts as [1], [2].\n\n"
            f"Ticket title: {title}\nTicket body: {body}\n\n"
            f"Sources:\n{context}\n\n"
            f"Question: {title} {body}"
        )
        try:
            text, provider = generate_with_fallback(self.settings, prompt)
            steps.append(f"draft: generated by provider '{provider}'")
            return text
        except ProviderError as exc:
            steps.append(f"draft: provider unavailable ({exc}); "
                         "used template draft from top source")
            top = results[0].chunk
            return (
                "Thanks for reaching out. Based on our help article "
                f"\"{top.title}\" ({top.source}):\n\n{top.text[:600]}\n\n"
                "If that doesn't solve it, reply here and a human will follow up."
            )

    # -- main loop ----------------------------------------------------------
    def process_ticket(self, title: str, body: str = "",
                       approve: bool = False) -> AgentResult:
        steps: list[str] = []
        category, priority = self._classify(title, body, steps)
        results = self._retrieve(title, body, steps)
        draft = self._draft(title, body, results, steps)
        sources = [r.chunk.source for r in results]

        if not results:
            return AgentResult(category, priority, draft, sources,
                               status="no_evidence", action=None, steps=steps)

        if not approve:
            steps.append("approval gate: NOT approved — no action taken")
            log.info("ticket processed, awaiting approval: %s", title)
            return AgentResult(category, priority, draft, sources,
                               status="awaiting_approval", action=None,
                               steps=steps)

        steps.append("approval gate: approved by human — acting")
        issue_title = f"[{category}/{priority}] {title}"
        action = self.github.create_issue(
            title=issue_title, body=draft, labels=[category, f"priority:{priority}"],
        )
        steps.append(f"act: create_issue (dry_run={action.get('dry_run')})")
        return AgentResult(category, priority, draft, sources,
                           status="acted", action=action, steps=steps)
